create table members (
    id bigint generated by default as identity primary key,
    email varchar(120) not null unique,
    password varchar(100) not null,
    name varchar(50) not null,
    phone varchar(30),
    role varchar(20) not null default 'USER',
    created_at timestamp not null default current_timestamp
);

create table products (
    id bigint generated by default as identity primary key,
    slug varchar(80) not null unique,
    name varchar(120) not null,
    category varchar(20) not null,          -- EEL | GIFT
    summary varchar(300),
    description text,
    price integer not null,
    weight varchar(100),
    origin varchar(100),
    storage varchar(200),
    shipping_info varchar(300),
    image_url varchar(300),
    gallery text,                           -- 실제 상품 사진 URL, 줄바꿈 구분
    features text,
    process text,
    cooking text,
    packaging text,
    faq text,                               -- "Q: ..." / "A: ..." 줄 단위
    stock integer not null default 0,
    active boolean not null default true,
    featured boolean not null default false,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);

create table product_options (
    id bigint generated by default as identity primary key,
    product_id bigint not null references products(id) on delete cascade,
    name varchar(100) not null,
    extra_price integer not null default 0,
    sort integer not null default 0
);

create table orders (
    id bigint generated by default as identity primary key,
    order_no varchar(30) not null unique,
    member_id bigint references members(id),
    guest_password varchar(100),
    orderer_name varchar(50) not null,
    orderer_phone varchar(30) not null,
    orderer_email varchar(120) not null,
    recipient_name varchar(50) not null,
    recipient_phone varchar(30) not null,
    zipcode varchar(10) not null,
    address1 varchar(200) not null,
    address2 varchar(200),
    memo varchar(300),
    gift_message varchar(500),
    items_amount integer not null,
    shipping_fee integer not null,
    total_amount integer not null,
    status varchar(30) not null,
    payment_method varchar(30),
    payment_key varchar(200),
    paid_at timestamp,
    carrier varchar(50),
    tracking_no varchar(50),
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);
create index idx_orders_member on orders(member_id);

create table order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references orders(id) on delete cascade,
    product_id bigint not null references products(id),
    product_name varchar(120) not null,
    option_name varchar(100),
    unit_price integer not null,
    quantity integer not null
);

create table reviews (
    id bigint generated by default as identity primary key,
    product_id bigint not null references products(id),
    member_id bigint not null references members(id),
    author_name varchar(50) not null,
    rating integer not null check (rating between 1 and 5),
    content varchar(2000) not null,
    created_at timestamp not null default current_timestamp,
    unique (product_id, member_id)
);

create table inquiries (
    id bigint generated by default as identity primary key,
    member_id bigint references members(id),
    name varchar(50) not null,
    email varchar(120) not null,
    title varchar(200) not null,
    content varchar(4000) not null,
    answer varchar(4000),
    created_at timestamp not null default current_timestamp,
    answered_at timestamp
);

create table articles (
    id bigint generated by default as identity primary key,
    slug varchar(80) not null unique,
    type varchar(20) not null,              -- STORY | GUIDE
    title varchar(200) not null,
    summary varchar(500),
    body text,
    image_url varchar(300),
    sort integer not null default 0,
    published boolean not null default true,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp
);
